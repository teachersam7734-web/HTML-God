// timeline.mjs: narration first. Turns a script (scenes with pre-roll, beats and gaps) plus the MEASURED duration of
// every voice line into absolute beat times, a total duration, an SRT file and a JS module the film page reads.
// Edit a line, regenerate its audio, re-run: every cue in the picture moves with it.
//
//   node timeline.mjs script.json --vo vo/ [--srt out.srt] [--js timeline.js] [--json timeline.json]
//
// script.json: { "scenes": [ { "id": "open", "pre": 1.2, "tail": 0.8,
//                              "beats": [ ["b1", "Skim first.", 0.4], ["b2", "Then scan.", 0.6] ] } ] }
//   a beat is [id, text shown in captions, gap after it in seconds]; vo/<id>.(wav|mp3|m4a|ogg) is measured with
//   ffprobe, or give "timings": { "b1": 1.31 } in script.json to skip measuring.
//
// verified: Node 24 + ffprobe 7.1 on Windows 10, with synthesised WAV lines (test-pipeline.mjs): totals and SRT
//           times match the measured durations to the millisecond.
// not verified: very long scripts; VO formats other than WAV in the test.
// Original HTML-Sensei code; the pre / gap / tail shape follows the Battle-of-Austerlitz-Film architecture (no
// licence: idea only).
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const { findFfmpeg } = await import(pathToFileURL(path.resolve(HERE, '../../../lib/discover.mjs')).href);

export function measure(file) {
  const ff = findFfmpeg();
  if (!ff.found || !ff.ffprobe) throw new Error('ffprobe not found: set FFMPEG_PATH');
  const r = spawnSync(ff.ffprobe, ['-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nw=1:nk=1', file], { encoding: 'utf8' });
  const d = parseFloat(r.stdout); if (!(d > 0)) throw new Error(`cannot measure ${file}`); return d;
}

export function build(script, timings) {
  let t = 0; const beats = {}, scenes = [];
  for (const s of script.scenes) {
    const start = t; t += s.pre || 0;
    for (const [id, text, gap = 0] of s.beats) {
      if (!(id in timings)) throw new Error(`no timing for beat ${id}`);
      beats[id] = { start: +t.toFixed(3), end: +(t + timings[id]).toFixed(3), text, scene: s.id };
      t += timings[id] + gap;
    }
    t += s.tail || 0; scenes.push({ id: s.id, start: +start.toFixed(3), end: +t.toFixed(3) });
  }
  return { total: +t.toFixed(3), scenes, beats };
}

const stamp = s => { const ms = Math.round(s * 1000), h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, sec = Math.floor(ms / 1000) % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')},${String(ms % 1000).padStart(3, '0')}`; };
// captions stay at least 1.8 s and at least the speech plus 0.6 s, but never overlap the next caption
export function srt(tl) {
  const list = Object.values(tl.beats).sort((a, b) => a.start - b.start);
  return list.map((b, i) => { const next = list[i + 1] ? list[i + 1].start : tl.total;
    const end = Math.min(next, Math.max(b.end + 0.6, b.start + 1.8, b.end));
    return `${i + 1}\n${stamp(b.start)} --> ${stamp(end)}\n${b.text}\n`; }).join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const a = process.argv.slice(2), opt = k => { const i = a.indexOf(k); return i >= 0 ? a[i + 1] : null; };
  const script = JSON.parse(fs.readFileSync(a[0], 'utf8'));
  const timings = { ...(script.timings || {}) };
  if (opt('--vo')) for (const s of script.scenes) for (const [id] of s.beats) if (!(id in timings)) {
    const f = ['wav', 'mp3', 'm4a', 'ogg'].map(e => path.join(opt('--vo'), `${id}.${e}`)).find(fs.existsSync);
    if (f) timings[id] = measure(f);
  }
  const tl = build(script, timings);
  if (opt('--srt')) fs.writeFileSync(opt('--srt'), srt(tl));
  if (opt('--json')) fs.writeFileSync(opt('--json'), JSON.stringify(tl, null, 2) + '\n');
  if (opt('--js')) fs.writeFileSync(opt('--js'), `// generated by timeline.mjs: do not edit, re-run it\nwindow.TIMELINE = ${JSON.stringify(tl)};\n`);
  console.log(`total ${tl.total} s, ${Object.keys(tl.beats).length} beats in ${tl.scenes.length} scenes`);
}
